import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  CLUSTER_LABELS,
  loadLibraryArticles,
  toSeoEntry,
  validateLibraryArticles,
} from "./library-shared.mjs";

const ROOT = path.resolve(process.cwd());
const LIBRARY_DIR = path.join(ROOT, "content", "library");
const GENERATED_TS = path.join(ROOT, "src", "content", "library", "index.generated.ts");
const GENERATED_SEO = path.join(ROOT, "server", "library-seo.generated.mjs");
const SITEMAP = path.join(ROOT, "public", "sitemap.xml");

const STATIC_SITEMAP = [
  { loc: "https://ksenia-ahmedova.ru/", lastmod: "" },
  { loc: "https://ksenia-ahmedova.ru/articles", lastmod: "" },
  { loc: "https://ksenia-ahmedova.ru/strah-otverzheniya", lastmod: "2026-09-11" },
  { loc: "https://ksenia-ahmedova.ru/boyus-prosit", lastmod: "2026-09-12" },
  { loc: "https://ksenia-ahmedova.ru/strah-otkaza-i-ugozhdenie", lastmod: "2026-09-13" },
  { loc: "https://ksenia-ahmedova.ru/posle-otkaza-hochu-ischeznut", lastmod: "2026-09-14" },
  { loc: "https://ksenia-ahmedova.ru/pochemu-ya-uchityvayu-chuzhie-zhelaniya", lastmod: "2026-11-18" },
  { loc: "https://ksenia-ahmedova.ru/pochemu-ya-zhdu-ot-muzha", lastmod: "2026-11-22" },
  { loc: "https://ksenia-ahmedova.ru/kogda-govoryat-net", lastmod: "2026-09-11" },
  { loc: "https://ksenia-ahmedova.ru/praktika-ne-otkazyvatsya-ot-sebya", lastmod: "" },
];

function esc(value) {
  return JSON.stringify(value);
}

async function main() {
  await mkdir(path.dirname(GENERATED_TS), { recursive: true });
  const all = await loadLibraryArticles(LIBRARY_DIR);
  const errors = validateLibraryArticles(all);
  if (errors.length) {
    console.error("Library validation failed:\n" + errors.map((e) => `- ${e}`).join("\n"));
    process.exit(1);
  }

  const published = all
    .filter((item) => item.status === "published")
    .sort((a, b) => String(b.date).localeCompare(String(a.date)));

  const ts = `/* Generated by server/build-library.mjs. Do not edit by hand. */
export type LibraryPractice = "kogda-net" | "otkaz-ot-sebya" | "none";

export type LibraryArticle = {
  slug: string;
  title: string;
  h1: string;
  description: string;
  author: string;
  date: string;
  updatedAt: string;
  sourceUrl: string;
  cluster: string;
  clusterLabel: string;
  related: string[];
  practice: LibraryPractice;
  practiceHref: string;
  cover: string;
  coverAlt: string;
  bodyHtml: string;
};

export const LIBRARY_CLUSTER_LABELS = ${esc(CLUSTER_LABELS)} as const;

export const libraryArticles: LibraryArticle[] = ${esc(
    published.map((item) => ({
      slug: item.slug,
      title: item.title,
      h1: item.h1,
      description: item.description,
      author: item.author,
      date: item.date,
      updatedAt: item.updatedAt,
      sourceUrl: item.sourceUrl,
      cluster: item.cluster,
      clusterLabel: item.clusterLabel,
      related: item.related,
      practice: item.practice,
      practiceHref: item.practiceHref,
      cover: item.cover,
      coverAlt: item.coverAlt,
      bodyHtml: item.bodyHtml,
    })),
  )};

export function getLibraryArticle(slug: string) {
  return libraryArticles.find((item) => item.slug === slug) || null;
}
`;

  const seoMap = Object.fromEntries(published.map((item) => [`/${item.slug}`, toSeoEntry(item)]));
  const bodies = Object.fromEntries(published.map((item) => [item.slug, item.bodyHtml]));
  const relatedCards = Object.fromEntries(
    published.map((item) => [
      item.slug,
      item.related
        .map((slug) => published.find((entry) => entry.slug === slug))
        .filter(Boolean)
        .slice(0, 3)
        .map((entry) => ({
          slug: entry.slug,
          h1: entry.h1,
          cover: entry.cover,
          coverAlt: entry.coverAlt,
        })),
    ]),
  );
  const practiceCta = Object.fromEntries(
    published
      .filter((item) => item.practiceHref)
      .map((item) => [
        item.slug,
        {
          href: item.practiceHref,
          practice: item.practice,
          label: "Пройти бесплатную практику",
        },
      ]),
  );
  const seoTs = `/* Generated by server/build-library.mjs. Do not edit by hand. */
export const LIBRARY_PAGE_SEO = ${esc(seoMap)};
export const LIBRARY_ARTICLE_HTML = ${esc(bodies)};
export const LIBRARY_RELATED_CARDS = ${esc(relatedCards)};
export const LIBRARY_PRACTICE_CTA = ${esc(practiceCta)};
export const LIBRARY_PUBLISHED_SLUGS = ${esc(published.map((item) => item.slug))};
`;

  const sitemapEntries = [
    ...STATIC_SITEMAP,
    ...published.map((item) => ({
      loc: `https://ksenia-ahmedova.ru/${item.slug}`,
      lastmod: item.updatedAt || item.date,
    })),
  ];
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapEntries
  .map((entry) => {
    const last = entry.lastmod ? `\n    <lastmod>${entry.lastmod}</lastmod>` : "";
    return `  <url>\n    <loc>${entry.loc}</loc>${last}\n  </url>`;
  })
  .join("\n")}
</urlset>
`;

  await writeFile(GENERATED_TS, ts, "utf8");
  await writeFile(GENERATED_SEO, seoTs, "utf8");
  await writeFile(SITEMAP, sitemap, "utf8");
  console.log(
    `Library build: ${published.length} published, ${all.length - published.length} drafts`,
  );
}

await main();
